import AppKit

enum ClipKind: String, Sendable, CaseIterable {
    case text, richText, image, files, url, color

    var symbol: String {
        switch self {
        case .text: "doc.plaintext"
        case .richText: "doc.richtext"
        case .image: "photo"
        case .files: "folder"
        case .url: "link"
        case .color: "paintpalette"
        }
    }

    var label: String {
        switch self {
        case .text: "Text"
        case .richText: "Rich text"
        case .image: "Image"
        case .files: "Files"
        case .url: "Link"
        case .color: "Color"
        }
    }
}

struct ClipItem: Identifiable, Equatable, Sendable {
    let id: UUID
    var createdAt: Date
    var lastUsedAt: Date
    var kind: ClipKind
    /// Short display string (≤ 2 KB, whitespace collapsed).
    var preview: String
    /// Lowercased, diacritic-folded text used for search (≤ 8 KB).
    var searchText: String
    var sourceBundleID: String?
    var pinned: Bool
    var byteSize: Int
    var contentHash: String
    /// Pasteboard types stored as blob files, in original order.
    var types: [String]
}

/// One representation read off the pasteboard.
struct Representation: Sendable {
    let type: String
    let data: Data
}

/// Everything needed to create a ClipItem, captured off the main thread.
struct Capture: Sendable {
    var reps: [Representation]
    var sourceBundleID: String?
    var date = Date()
}

extension NSPasteboard.PasteboardType {
    static let concealed = Self("org.nspasteboard.ConcealedType")
    static let transient = Self("org.nspasteboard.TransientType")
    static let autoGenerated = Self("org.nspasteboard.AutoGeneratedType")
    static let source = Self("org.nspasteboard.source")
    static let fileURLs = Self("public.file-url")
    static let colorType = Self("com.apple.cocoa.pasteboard.color")
    static let urlType = Self("public.url")
}
